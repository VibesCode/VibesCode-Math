# Generates TanArctan12.lean: plain-Lean (core only) proofs that A n does not divide B n for Ono's 12
# exceptional indices, via a chain of checkpoints gp m = (literal, literal), each checked by the kernel.
import sys
sys.set_int_max_str_digits(0)
targets = [15,17,80,82,395,397,1904,1906,9163,9165,44086,44088]
CH = 1500
cps = sorted(set(list(range(CH, 44088, CH)) + targets))
A,B = 1,0; vals = {}
for k in range(1, 44089):
    A, B = A - k*B, B + k*A
    if k in cps: vals[k] = (A,B)
L = []
L.append('''/-! Plain Lean 4 (core only).
Z_n = ∏_{k=1}^n (1 + k i) = A n + B n i, same as formal-conjectures `Arxiv.«2607.05739».gaussProd`
(written here as a recursion on n instead of a Finset product, since Mathlib is unavailable).
x_n = B n / A n is an integer iff `A n ∣ B n` (that is formal-conjectures' `IsIntegerValue`).
We prove `¬ A n ∣ B n` for Ono's twelve exceptional indices in [5, 6·10^4]. Generated by gen.py. -/

def step (k : Nat) (p : Int × Int) : Int × Int := (p.1 - (k : Int) * p.2, p.2 + (k : Int) * p.1)

def gp : Nat → Int × Int
  | 0 => (1, 0)
  | n + 1 => step (n + 1) (gp n)

def A (n : Nat) : Int := (gp n).1
def B (n : Nat) : Int := (gp n).2

/-- `run m p j` applies the factors (1 + (m+1) i), ..., (1 + (m+j) i) to `p`. -/
def run (m : Nat) (p : Int × Int) : Nat → Int × Int
  | 0 => p
  | j + 1 => step (m + j + 1) (run m p j)

theorem gp_run (m j : Nat) : gp (m + j) = run m (gp m) j := by
  induction j with
  | zero => rfl
  | succ j ih => show step (m + j + 1) (gp (m + j)) = step (m + j + 1) (run m (gp m) j); rw [ih]

/-- controls: the four known integer values n = 1..4 -/
theorem ctrl : A 1 ∣ B 1 ∧ A 2 ∣ B 2 ∧ A 3 ∣ B 3 ∧ A 4 ∣ B 4 := by decide +kernel
''')
prev = 0
for c in cps:
    a,b = vals[c]
    if prev == 0:
        L.append(f'theorem cp{c} : gp {c} = ({a}, {b}) := by decide +kernel\n')
    else:
        L.append(f'theorem cp{c} : gp {c} = ({a}, {b}) := by\n  rw [show ({c} : Nat) = {prev} + {c-prev} from rfl, gp_run, cp{prev}]; decide +kernel\n')
    if c in targets:
        L.append(f'theorem not_int_{c} : ¬ A {c} ∣ B {c} := by\n  unfold A B; rw [cp{c}]; decide +kernel\n')
    prev = c
L.append('theorem ono_exceptional_not_integer :\n    ' + ' ∧ '.join(f'¬ A {t} ∣ B {t}' for t in targets) + ' :=\n  ⟨' + ', '.join(f'not_int_{t}' for t in targets) + '⟩\n')
open('TanArctan12.lean','w').write('\n'.join(L))
